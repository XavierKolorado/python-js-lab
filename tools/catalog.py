def py(folder, path, *text, **options):
    return Exercise("python", folder, path, *text, **options)


def js(folder, path, *text, **options):
    return Exercise("javascript", folder, path, *text, **options)


def web(folder, path, *text, **options):
    return Exercise("javascript", folder, path, *text, browser=True, **options)


