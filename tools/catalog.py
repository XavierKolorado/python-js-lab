"""Single source of truth for the 100 exercises: documentation text and example runs."""

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Level:
    language: str
    folder: str
    number: int
    title_pt: str
    title_en: str


@dataclass(frozen=True)
class Exercise:
    language: str
    folder: str
    path: str  # relative to language/folder; a directory for browser projects
    title_pt: str
    title_en: str
    description_pt: str
    description_en: str
    goal_pt: str
    goal_en: str
    concepts: str
    expected_pt: str
    expected_en: str
    args: tuple = ()
    stdin: str = ""
    network: bool = False
    browser: bool = False
    hidden_args: tuple = field(default=())  # passed to the run, omitted from the docs

    @property
    def number(self) -> int:
        return int(self.path[:2])

    @property
    def repo_path(self) -> str:
        return f"{self.language}/{self.folder}/{self.path}"


